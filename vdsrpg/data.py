def exp_needed(level: int) -> int:
    """Опыт, нужный для перехода с `level` на следующий уровень."""
    if level < 1:
        return _BASE_EXP[1]
    if level in _BASE_EXP:
        return _BASE_EXP[level]
    v = _BASE_EXP[4]
    for L in range(5, level + 1):
        if L <= 25:
            v = v * 1.1265
        elif L <= 50:
            v = v * 1.04
        else:
            v = v * 1.015
    return int(v)


def chapter_mult(chapter: int) -> int:
    """Множитель опыта от главы: 1:×1, 2:×12, 3:×18 ... 9:×54 (далее ×6*глава)."""
    return 1 if chapter == 1 else 6 * chapter


