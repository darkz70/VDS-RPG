META_CYCLE = {1: 4, 4: 3, 3: 2, 2: 1}  # цикл 1 подавляет 4, 4 подавляет 3, 3 подавляет 2, 2 подавляет 1

_AFF_TO_CYCLE = {}
_AFF_TO_INDEX = {}
for _c, _lst in AFF_CYCLES.items():
    for _i, _a in enumerate(_lst):
        _AFF_TO_CYCLE[_a] = _c
        _AFF_TO_INDEX[_a] = _i


def cycle_of(affinity: str) -> int:
    return _AFF_TO_CYCLE.get(affinity, 1)


def suppresses(a: str, b: str) -> bool:
    """True, если особенность a подавляет особенность b.

    Сначала проверяется подавление внутри цикла, затем мета-подавление циклов.
    """
    ca, cb = cycle_of(a), cycle_of(b)
    if ca == cb:
        return (_AFF_TO_INDEX[a] + 1) % 10 == _AFF_TO_INDEX[b]
    return META_CYCLE.get(ca) == cb


