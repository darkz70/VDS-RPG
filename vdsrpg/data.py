def darkness_for_loc(chapter: int, loc: int) -> int:
    if chapter == 1:
        return DARKNESS_CH1_FIRST if loc <= 18 else DARKNESS_CH1_SECOND
    mult = chapter_mult(chapter)
    base = DARKNESS_CH1_FIRST if loc <= 18 else DARKNESS_CH1_SECOND
    return int(base * mult * (1 + 0.5 * (chapter - 1)))


def gen_locations(chapter: int) -> list[dict]:
    """35 локаций главы."""
    locs = []
    for n in range(1, LOCS_PER_CHAPTER + 1):
        theme = THEMES[(n - 1) % len(THEMES)]
        if chapter == 1:
            if n <= 5:
                mobs = ["weak"] * 5
            elif n <= 10:
                mobs = ["weak"] * 6 + ["medium"] * 2
            elif n == 11:
                mobs = ["boss"]
            elif n in (23, 35):
                mobs = ["boss"]
            else:
                mobs = ["medium"] * 3
        else:
            if n in BOSS_LOCS:
                mobs = ["boss"]
            elif n <= 17:
                mobs = ["strong"] * 3
            else:
                mobs = ["strong"] * 5
        locs.append({
            "n": n,
            "mobs": mobs,
            "theme": theme,
            "darkness": darkness_for_loc(chapter, n),
            "is_boss": n in BOSS_LOCS,
            "materials": n in MATERIAL_LOCS,
        })
    return locs


